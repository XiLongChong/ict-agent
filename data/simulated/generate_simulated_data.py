def write_csv(name: str, header: list[str], rows: list[list[object]]) -> None:
    path = OUT / name
    with path.open("w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(header)
        for r in rows:
            w.writerow(r)
    print(f"written {path.name}: {len(rows)} rows")


